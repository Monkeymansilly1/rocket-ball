"""Bundle the original car geometry as native Three.js models.
Run: python tools/bundle-car-bodies.py [octane fennec scorpion]
The real bodies and wheel pivots need no loader, image, GLB or binary requests.
Existing glTF/GLB assets remain available for optional texture upgrades.
"""
import base64, json, struct, sys
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
SOURCES={'octane':'Octane by Jako (CC BY 4.0)','fennec':'Fennec.fbx','scorpion':'Scorpion[2].fbx'}
def read_asset(folder):
 if (folder/'scene.glb').exists():
  content=(folder/'scene.glb').read_bytes()
  magic,version,total=struct.unpack_from('<III',content)
  assert magic==0x46546c67 and version==2 and total==len(content)
  offset=12;document=None;binary=None
  while offset<len(content):
   size,kind=struct.unpack_from('<II',content,offset);chunk=content[offset+8:offset+8+size];offset+=size+8
   if kind==0x4e4f534a:document=json.loads(chunk)
   elif kind==0x004e4942:binary=chunk
  assert document is not None and binary is not None
  return document,binary
 document=json.loads((folder/'scene.gltf').read_text())
 assert len(document['buffers'])==1
 return document,(folder/document['buffers'][0]['uri']).read_bytes()
def bundle(name):
 folder=ROOT/'assets'/name;document,binary=read_asset(folder)
 assert all('sparse' not in a for a in document['accessors'])
 for material in document['materials']:
  for key in ['extensions','normalTexture','occlusionTexture','emissiveTexture','alphaMode','alphaCutoff']:material.pop(key,None)
  pbr=material.get('pbrMetallicRoughness',{})
  for key in ['baseColorTexture','metallicRoughnessTexture']:pbr.pop(key,None)
  if name=='scorpion' and material['name']=='mat_4.002':pbr['baseColorFactor']=[.22,.24,.26,1]
  elif name=='scorpion' and material['name']=='mat_7.002':pbr['baseColorFactor']=[.06,.07,.08,1]
 for key in ['images','textures','samplers','extensionsUsed','extensionsRequired']:document.pop(key,None)
 document['buffers']=[{'byteLength':len(binary)}]
 symbol='Rocket'+name.title()+'Body'
 output=FACTORY.replace('__DOCUMENT__',json.dumps(document,separators=(',',':'))).replace('__BINARY__',base64.b64encode(binary).decode()).replace('__SYMBOL__',symbol).replace('__NAME__',json.dumps(name)).replace('__SOURCE__',json.dumps(SOURCES[name]))
 notice='// Generated by tools/bundle-car-bodies.py. See the model credits in this folder.\n'
 (folder/'body.js').write_text(notice+output)
 print(name,len(output),'bytes')

FACTORY = r'''
(function(root){
'use strict';
const data=__DOCUMENT__;
const encoded='__BINARY__';
root.__SYMBOL__={
  create(THREE){
    const raw=atob(encoded),bytes=new Uint8Array(raw.length);
    for(let i=0;i<raw.length;i++)bytes[i]=raw.charCodeAt(i);
    const buffer=bytes.buffer;
    const components={5120:Int8Array,5121:Uint8Array,5122:Int16Array,5123:Uint16Array,5125:Uint32Array,5126:Float32Array};
    const widths={SCALAR:1,VEC2:2,VEC3:3,VEC4:4,MAT4:16};
    function attribute(index){
      const accessor=data.accessors[index],view=data.bufferViews[accessor.bufferView];
      const Typed=components[accessor.componentType],width=widths[accessor.type];
      const offset=(view.byteOffset||0)+(accessor.byteOffset||0);
      const stride=view.byteStride||width*Typed.BYTES_PER_ELEMENT;
      if(stride!==width*Typed.BYTES_PER_ELEMENT)throw new Error('Car bundle requires packed mesh attributes');
      return new THREE.BufferAttribute(new Typed(buffer,offset,accessor.count*width),width,!!accessor.normalized);
    }
    const materials=data.materials.map(source=>{
      const pbr=source.pbrMetallicRoughness||{},color=pbr.baseColorFactor||[.5,.5,.5,1];
      const material=new THREE.MeshStandardMaterial({
        color:new THREE.Color().fromArray(color),metalness:pbr.metallicFactor??1,
        roughness:pbr.roughnessFactor??1,side:source.doubleSided?THREE.DoubleSide:THREE.FrontSide
      });
      material.name=source.name;
      return material;
    });
    const attributes={POSITION:'position',NORMAL:'normal',TEXCOORD_0:'uv',TANGENT:'tangent',COLOR_0:'color'};
    const meshes=data.meshes.map(mesh=>mesh.primitives.map(primitive=>{
      const geometry=new THREE.BufferGeometry();
      for(const [key,index] of Object.entries(primitive.attributes)){
        if(attributes[key])geometry.setAttribute(attributes[key],attribute(index));
      }
      if(primitive.indices!==undefined)geometry.setIndex(attribute(primitive.indices));
      geometry.computeBoundingBox();geometry.computeBoundingSphere();
      return {geometry,material:materials[primitive.material]};
    }));
    const nodes=data.nodes.map(source=>{
      const node=new THREE.Group();node.name=source.name||'';
      if(source.translation)node.position.fromArray(source.translation);
      if(source.rotation)node.quaternion.fromArray(source.rotation);
      if(source.scale)node.scale.fromArray(source.scale);
      if(source.matrix){node.matrix.fromArray(source.matrix);node.matrix.decompose(node.position,node.quaternion,node.scale);}
      if(source.mesh!==undefined)for(const part of meshes[source.mesh])node.add(new THREE.Mesh(part.geometry,part.material));
      return node;
    });
    data.nodes.forEach((source,i)=>(source.children||[]).forEach(child=>nodes[i].add(nodes[child])));
    const model=new THREE.Group();model.name=__NAME__+' Bundled Body';
    for(const node of data.scenes[data.scene||0].nodes)model.add(nodes[node]);
    model.userData.source=__SOURCE__;model.userData.vehicleModel=__NAME__;
    return model;
  }
};
})(typeof window==='undefined'?globalThis:window);
'''

if __name__=='__main__':
 for name in sys.argv[1:] or ['octane','fennec','scorpion']:
  if name not in SOURCES:raise SystemExit('Unknown car: '+name)
  bundle(name)
